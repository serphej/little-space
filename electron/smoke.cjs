const assert = require('node:assert/strict')
const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds))
async function waitFor(check, description) {
  for (let attempt = 0; attempt < 100; attempt++) {
    try { if (await check()) return } catch { /* Renderer may still be loading. */ }
    await delay(100)
  }
  throw new Error(`Timed out: ${description}`)
}
async function run({ app, dashboard, dog, tray, applyPreference, repairBounds, getPetState, getPreferences, showDashboard, bubble, reminders, tickReminders }) {
  await waitFor(() => dashboard.webContents.executeJavaScript("Boolean(document.querySelector('.greeting') && window.lauDesktop)"), 'dashboard boot')
  await waitFor(() => dog.webContents.executeJavaScript("Boolean(window.lauDog && document.querySelector('#dog'))"), 'dog boot')
  await waitFor(() => dog.webContents.executeJavaScript("document.querySelector('#dog').getContext('2d').getImageData(0, 0, 48, 40).data.some(value => value !== 0)"), 'dog pixels painted')
  console.log(`LAU_SMOKE_READY:${process.env.LAU_SMOKE_PHASE}`)
  const security = dashboard.webContents.getLastWebPreferences()
  assert.equal(security.contextIsolation, true); assert.equal(security.nodeIntegration, false); assert.equal(security.sandbox, true)
  assert.equal(await dashboard.webContents.executeJavaScript('typeof require'), 'undefined')
  assert.equal(await dashboard.webContents.executeJavaScript('typeof window.lauDog'), 'undefined')
  assert.equal(await dog.webContents.executeJavaScript('typeof window.lauDesktop'), 'undefined')
  assert.equal(dog.isFocusable(), false)
  assert.equal(dog.isAlwaysOnTop(), true)
  assert.equal(tray.isDestroyed(), false)
  assert.equal(dog.getSize()[0], getPreferences().size)
  const rejected = await dashboard.webContents.executeJavaScript("window.lauDesktop.setPreference('size', 900).then(() => false, () => true)")
  assert.equal(rejected, true)
  if (process.env.LAU_SMOKE_PHASE === 'write') {
    await dashboard.webContents.executeJavaScript("document.querySelector('.section-title .primary').click()")
    await waitFor(() => dashboard.webContents.executeJavaScript("Boolean(document.querySelector('.editor input[data-autofocus]'))"), 'task editor')
    await dashboard.webContents.executeJavaScript(`(() => { const input = document.querySelector('.editor input[data-autofocus]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'Desktop persistence test'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
    await delay(100)
    await dashboard.webContents.executeJavaScript("document.querySelector('.editor').requestSubmit()")
    await waitFor(() => dashboard.webContents.executeJavaScript("JSON.parse(localStorage.getItem('lau-dashboard-v2') || '{}').tasks?.some(task => task.title === 'Desktop persistence test')"), 'task saving')
    await dashboard.webContents.executeJavaScript(`(() => { const task = JSON.parse(localStorage.getItem('lau-dashboard-v2')).tasks[0]; const select = document.querySelector('#focus-task'); Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set.call(select, task.id); select.dispatchEvent(new Event('change', { bubbles: true })); })()`)
    await delay(100)
    await dashboard.webContents.executeJavaScript("document.querySelector('.timer-actions .primary').click()")
    await waitFor(() => getPetState().mode === 'sleep', 'focus sleeping animation')
    await dashboard.webContents.executeJavaScript("document.querySelector('.task-check').click()")
    await waitFor(() => getPetState().mode === 'happy', 'task happy animation')
    await waitFor(() => dashboard.webContents.executeJavaScript("JSON.parse(localStorage.getItem('lau-dashboard-v2')).tasks[0].completed"), 'completion persistence')
    await delay(2600)
    await waitFor(() => getPetState().mode === 'sleep', 'return to sleep after happy animation')
    const preview = await dog.webContents.capturePage()
    assert.equal(preview.isEmpty(), false)
    assert.equal(preview.toBitmap()[3], 0, 'Dog window background must be transparent')
    require('node:fs').writeFileSync(require('node:path').join(process.env.LAU_SMOKE_USER_DATA, 'dog-preview.png'), preview.toPNG())
    applyPreference('paused', true)
    applyPreference('size', 128)
    applyPreference('visible', false)
    assert.equal(dog.isVisible(), false)
    assert.equal(tray.isDestroyed(), false)
    assert.equal(dog.getSize()[0], 128)
    applyPreference('visible', true)
    dog.setPosition(-100000, -100000)
    repairBounds()
    const bounds = dog.getBounds()
    const { screen } = require('electron')
    const area = screen.getDisplayNearestPoint({ x: bounds.x, y: bounds.y }).workArea
    assert.ok(bounds.x >= area.x && bounds.y >= area.y)
    assert.ok(bounds.x + bounds.width <= area.x + area.width)
    assert.ok(bounds.y + bounds.height <= area.y + area.height)
    await waitFor(() => { showDashboard(); return dashboard.isVisible() }, 'dashboard visibility')
    dashboard.close()
    assert.equal(dashboard.isDestroyed(), false)
    assert.equal(dashboard.isVisible(), false)
    assert.equal(dog.isDestroyed(), false)
    assert.equal(tray.isDestroyed(), false)
    await waitFor(() => { showDashboard(); return dashboard.isVisible() }, 'dashboard reopening')
    dashboard.hide()
    await dashboard.webContents.executeJavaScript("localStorage.setItem('lau-smoke-marker', 'saved')")
    await waitFor(()=>bubble.webContents.executeJavaScript('Boolean(window.lauBubble)'), 'bubble boot')
    assert.equal(bubble.isFocusable(),process.platform==='win32')
    assert.equal(bubble.webContents.getLastWebPreferences().nodeIntegration,false)
    assert.equal(await bubble.webContents.executeJavaScript('typeof window.lauDesktop'),'undefined')
    reminders.changeSettings({pauseDuringFocus:false,dueTime:'23:59'})
    reminders.state.nextCheckAt=Date.now()-1;reminders.state.lastShownAt=0;reminders.blockUntil=0;tickReminders()
    await waitFor(()=>bubble.webContents.executeJavaScript("!document.querySelector('#panel').hidden"),'general bubble rendering')
    assert.equal(reminders.active.kind,'general')
    bubble.showInactive()
    await delay(250)
    assert.equal(bubble.isFocused(),false,'Showing a reminder must not activate it')
    const point=await bubble.webContents.executeJavaScript("(()=>{const r=document.querySelector('#actions button').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2),height:innerHeight}})()")
    assert.ok(point.x>0&&point.y>0&&point.y<point.height)
    if(process.platform==='win32') {
      const bounds=bubble.getBounds()
      const nativePoint=screen.dipToScreenPoint({x:bounds.x+point.x,y:bounds.y+point.y})
      const script=`Add-Type -TypeDefinition 'using System;using System.Runtime.InteropServices;public class LauMouse {[StructLayout(LayoutKind.Sequential)] public struct Point {public int X;public int Y;}[DllImport("user32.dll")] public static extern bool GetCursorPos(out Point p);[DllImport("user32.dll")] public static extern bool SetCursorPos(int x,int y);[DllImport("user32.dll")] public static extern void mouse_event(uint f,uint x,uint y,uint d,UIntPtr e);}'
$original=New-Object LauMouse+Point
[LauMouse]::GetCursorPos([ref]$original)|Out-Null
try {
 [LauMouse]::SetCursorPos(${nativePoint.x},${nativePoint.y})|Out-Null
 Start-Sleep -Milliseconds 100
 [LauMouse]::mouse_event(2,0,0,0,[UIntPtr]::Zero)
 Start-Sleep -Milliseconds 100
 [LauMouse]::mouse_event(4,0,0,0,[UIntPtr]::Zero)
} finally {[LauMouse]::SetCursorPos($original.X,$original.Y)|Out-Null}
`
      await require('node:util').promisify(require('node:child_process').execFile)('powershell.exe',['-NoProfile','-NonInteractive','-Command',script],{windowsHide:true})
    } else {
      bubble.webContents.sendInputEvent({type:'mouseDown',x:point.x,y:point.y,button:'left',clickCount:1})
      bubble.webContents.sendInputEvent({type:'mouseUp',x:point.x,y:point.y,button:'left',clickCount:1})
    }
    await waitFor(()=>dashboard.isVisible(),'Open tasks via bubble mouse click')
    assert.equal(reminders.active,null)
    dashboard.hide()
    const lateOpen=await bubble.webContents.executeJavaScript("window.lauBubble.action('expired-open-test','open')")
    assert.equal(lateOpen,true)
    assert.equal(dashboard.isVisible(),true)
    dashboard.hide()
    reminders.state.nextCheckAt=Date.now()-1;reminders.state.lastShownAt=0;tickReminders()
    await waitFor(()=>bubble.webContents.executeJavaScript("!document.querySelector('#panel').hidden"),'general bubble after opening tasks')
    await bubble.webContents.executeJavaScript("document.querySelector('#close').click()")
    await waitFor(()=>!reminders.active,'bubble dismissal')
    assert.equal(dashboard.isVisible(),false)
    await dashboard.webContents.executeJavaScript("document.querySelector('.section-title .primary').click()")
    await waitFor(()=>dashboard.webContents.executeJavaScript("Boolean(document.querySelector('.editor input[data-autofocus]'))"),'reminder task editor')
    await dashboard.webContents.executeJavaScript("(()=>{const input=document.querySelector('.editor input[data-autofocus]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'Reminder completion test');input.dispatchEvent(new Event('input',{bubbles:true}))})()")
    await delay(100)
    await dashboard.webContents.executeJavaScript("document.querySelector('.editor').requestSubmit()")
    await waitFor(()=>dashboard.webContents.executeJavaScript("JSON.parse(localStorage.getItem('lau-dashboard-v2')).tasks.length===2"),'second task saved')
    await dashboard.webContents.executeJavaScript("(()=>{const task=JSON.parse(localStorage.getItem('lau-dashboard-v2')).tasks[1];const select=document.querySelector('#focus-task');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(select,task.id);select.dispatchEvent(new Event('change',{bubbles:true}))})()")
    await waitFor(()=>reminders.context?.selectedTaskId===reminders.context?.tasks[1]?.id,'selection synchronized')
    reminders.state.nextCheckAt=Date.now()-1;reminders.state.lastShownAt=0;reminders.blockUntil=0;tickReminders()
    await waitFor(()=>bubble.webContents.executeJavaScript("document.querySelector('#actions button')?.textContent==='Done'"),'selected task controls')
    assert.equal(reminders.active.taskId,reminders.context.tasks[1].id)
    const reminderTaskId=reminders.active.taskId
    const bubbleBounds=bubble.getBounds()
    const bubbleArea=screen.getDisplayNearestPoint({x:bubbleBounds.x,y:bubbleBounds.y}).workArea
    assert.ok(bubbleBounds.x>=bubbleArea.x&&bubbleBounds.y>=bubbleArea.y)
    assert.ok(bubbleBounds.x+bubbleBounds.width<=bubbleArea.x+bubbleArea.width)
    assert.ok(bubbleBounds.y+bubbleBounds.height<=bubbleArea.y+bubbleArea.height)
    const bubbleCapture=await bubble.webContents.capturePage()
    assert.equal(bubbleCapture.toBitmap()[3],0,'Bubble margins must be transparent')
    await bubble.webContents.executeJavaScript("document.querySelectorAll('#actions button')[1].click()")
    await waitFor(()=>!reminders.active,'still working dismisses')
    assert.ok(reminders.state.nextCheckAt>Date.now()+29*60000)
    reminders.state.nextCheckAt=Date.now()-1;reminders.state.lastShownAt=0;tickReminders()
    await waitFor(()=>bubble.webContents.executeJavaScript("document.querySelector('#actions button')?.textContent==='Done' && !document.querySelector('#panel').hidden"),'next check-in')
    await bubble.webContents.executeJavaScript("document.querySelectorAll('#actions button')[2].click()")
    await waitFor(()=>!reminders.active,'snooze dismisses')
    assert.ok(reminders.state.snoozes[reminderTaskId]>Date.now()+14*60000)
    const persistedReminders=JSON.parse(require('node:fs').readFileSync(require('node:path').join(process.env.LAU_SMOKE_USER_DATA,'reminders.json'),'utf8'))
    assert.equal(persistedReminders.snoozes[reminderTaskId],reminders.state.snoozes[reminderTaskId])
    assert.equal(dashboard.isVisible(),false)
    delete reminders.state.snoozes[reminderTaskId]
    reminders.state.nextCheckAt=Date.now()-1;reminders.state.lastShownAt=0;tickReminders()
    await waitFor(()=>bubble.webContents.executeJavaScript("!document.querySelector('#panel').hidden"),'bubble after test snooze cleared')
    await bubble.webContents.executeJavaScript("document.querySelector('#actions button').click()")
    await waitFor(()=>dashboard.webContents.executeJavaScript("JSON.parse(localStorage.getItem('lau-dashboard-v2')).tasks[1].completed"),'bubble Done persisted through React')
    await waitFor(()=>reminders.state.commands.length===0,'completion acknowledged')
    assert.equal(dashboard.isVisible(),false)
    assert.equal(getPetState().mode,'happy')
    reminders.testMode(true)
    console.log('LAU_REMINDERS_PASS')
    await checkWebApp()
  } else {
    const saved = await dashboard.webContents.executeJavaScript("({ marker: localStorage.getItem('lau-smoke-marker'), data: JSON.parse(localStorage.getItem('lau-dashboard-v2')) })")
    assert.equal(saved.marker, 'saved')
    assert.equal(saved.data.tasks[0].title, 'Desktop persistence test')
    assert.equal(saved.data.tasks[0].completed, true)
    assert.equal(saved.data.timer.state, 'running')
    assert.equal(getPreferences().paused, true)
    assert.equal(getPreferences().size, 128)
  }
  console.log(`LAU_SMOKE_PASS:${process.env.LAU_SMOKE_PHASE}`)
  app.quit()
}
module.exports = { run }

async function checkWebApp() {
  const { BrowserWindow, session } = require('electron')
  const web = new BrowserWindow({ show: false, webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false } })
  try {
    await web.loadURL(process.env.LAU_SMOKE_WEB_URL)
    await waitFor(() => web.webContents.executeJavaScript("Boolean(document.querySelector('.greeting'))"), 'ordinary web render')
    assert.equal(await web.webContents.executeJavaScript('typeof window.lauDesktop'), 'undefined')
    await web.webContents.executeJavaScript("document.querySelector('.window-bar .icon-button').click()")
    await waitFor(() => web.webContents.executeJavaScript("Boolean(document.querySelector('.settings-content'))"), 'web settings')
    assert.equal(await web.webContents.executeJavaScript("Array.from(document.querySelectorAll('h3')).some(heading => heading.textContent.includes('Mochi'))"), false)
    await web.webContents.executeJavaScript("document.querySelector('.modal-header .icon-button').click(); document.querySelector('.section-title .primary').click()")
    await waitFor(() => web.webContents.executeJavaScript("Boolean(document.querySelector('.editor'))"), 'web new task')
    await web.webContents.executeJavaScript("(() => { const input = document.querySelector('.editor input[data-autofocus]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'Web task still works'); input.dispatchEvent(new Event('input', { bubbles: true })); })()")
    await delay(100)
    await web.webContents.executeJavaScript("document.querySelector('.editor').requestSubmit()")
    await waitFor(() => web.webContents.executeJavaScript("Boolean(document.querySelector('.task-check'))"), 'web task')
    await web.webContents.executeJavaScript("document.querySelector('.task-check').click()")
    await waitFor(() => web.webContents.executeJavaScript("JSON.parse(localStorage.getItem('lau-dashboard-v2')).tasks[0].completed"), 'web task completion')
    await web.webContents.executeJavaScript("navigator.serviceWorker.ready.then(() => caches.keys()).then(keys => { if (!keys.some(key => key.startsWith('lau-offline-'))) throw new Error('Offline cache missing') })")
    session.defaultSession.enableNetworkEmulation({ offline: true })
    await new Promise((resolve, reject) => {
      const timeout = setTimeout(() => reject(new Error('Offline reload timed out')), 10000)
      web.webContents.once('did-finish-load', () => { clearTimeout(timeout); resolve() })
      web.webContents.once('did-fail-load', (_event, code, message) => { clearTimeout(timeout); reject(new Error(`${code}: ${message}`)) })
      web.reload()
    })
    await waitFor(() => web.webContents.executeJavaScript("Boolean(document.querySelector('.greeting') && document.querySelector('.task-check')?.checked)"), 'offline dashboard and saved task')
    console.log('LAU_WEB_OFFLINE_PASS')
  } finally { session.defaultSession.disableNetworkEmulation(); web.destroy() }
}
